#!/usr/bin/env bash
# Writes LICENSES/THIRD-PARTY.md: every third-party Rust crate built into Qiyas and its command
# line and MCP bridge (normal dependencies on Linux, Windows and macOS; no build or dev ones), and
# every JavaScript package in the app's window (the production dependencies of package.json and
# theirs), each with its version and licence. LICENSES/ ships in every installer
# (tauri.bundle.conf.json). Run it after a dependency changes and before a release, then commit
# the file.
#   scripts/third-party.sh
set -euo pipefail
cd "$(dirname "$0")/.."

out=LICENSES/THIRD-PARTY.md
tmp=$(mktemp)
trap 'rm -f "$tmp"' EXIT

{
  echo "# Third-party software in Qiyas"
  echo
  echo "Generated by \`scripts/third-party.sh\`; do not edit by hand. The licence texts of the"
  echo "MPL-2.0, Apache-2.0, BSD, Zlib and BSL-1.0 code are in this folder; see \`README.md\` for"
  echo "where to get the source of the MPL-2.0 libraries."
  echo
  echo "## Rust crates"
  echo
  echo "| Crate | Version | Licence | Source |"
  echo "|---|---|---|---|"
  cargo tree --offline -e normal --prefix none --workspace \
    --target x86_64-unknown-linux-gnu --target x86_64-pc-windows-msvc \
    --target aarch64-apple-darwin --target x86_64-apple-darwin \
    --format '{p}|{l}' |
    sed 's/ (\*)$//' |
    grep -v -e ' (/' -e '^$' |
    sort -u |
    awk -F'|' '{
      split($1, p, " ");
      version = substr(p[2], 2);
      source = "crates.io";
      if (match($1, /\(https?:[^)]*\)/)) {
        source = substr($1, RSTART + 1, RLENGTH - 2);
        sub(/\?rev=[^#]*#/, " @ ", source);
      }
      licence = ($2 == "") ? "not stated" : $2;
      printf "| %s | %s | %s | %s |\n", p[1], version, licence, source;
    }'
  echo
  echo "## JavaScript packages (the app's window)"
  echo
  echo "| Package | Version | Licence |"
  echo "|---|---|---|"
  node - <<'NODE'
const fs = require("fs");
const path = require("path");
// Node's lookup: <dir>/node_modules/<name>, then each parent's.
function find(name, from) {
  for (let dir = from; ; dir = path.dirname(dir)) {
    const candidate = path.join(dir, "node_modules", name);
    if (fs.existsSync(path.join(candidate, "package.json"))) return fs.realpathSync(candidate);
    if (path.dirname(dir) === dir) return null;
  }
}
const root = JSON.parse(fs.readFileSync("package.json", "utf8"));
const seen = new Map();
const queue = Object.keys(root.dependencies || {}).map((name) => [name, process.cwd()]);
while (queue.length) {
  const [name, from] = queue.shift();
  const dir = find(name, from);
  if (!dir) throw new Error(`${name} is not installed: run pnpm install`);
  const pkg = JSON.parse(fs.readFileSync(path.join(dir, "package.json"), "utf8"));
  const key = `${pkg.name}@${pkg.version}`;
  if (seen.has(key)) continue;
  const licence = typeof pkg.license === "string" ? pkg.license : (pkg.license && pkg.license.type) || "not stated";
  seen.set(key, [pkg.name, pkg.version, licence]);
  for (const dep of Object.keys(pkg.dependencies || {})) queue.push([dep, dir]);
}
for (const [name, version, licence] of [...seen.values()].sort((a, b) => (a[0] + a[1]).localeCompare(b[0] + b[1]))) {
  console.log(`| ${name} | ${version} | ${licence} |`);
}
NODE
  echo
  echo "## Native libraries and models installed beside the app"
  echo
  echo 'Not crates: `scripts/pdfium.sh` and `scripts/ocr.sh` install them, each download checked'
  echo "against its SHA-256. Versions are in those scripts."
  echo
  echo "| Component | Licence | Text |"
  echo "|---|---|---|"
  echo "| pdfium (bblanchon/pdfium-binaries) | BSD-3-Clause | pdfium-BSD-3.txt |"
  echo "| ONNX Runtime | MIT | onnxruntime-MIT.txt (its third-party notices ship beside the runtime) |"
  echo "| PP-OCRv5 detector, Arabic recogniser and dictionary (PaddlePaddle) | Apache-2.0 | oar-ocr-Apache-2.0.txt |"
  echo "| Oniguruma (built into onig_sys) | BSD-2-Clause | Oniguruma-BSD-2-Clause.txt |"
} >"$tmp"

mv "$tmp" "$out"
trap - EXIT
echo "wrote $out"
