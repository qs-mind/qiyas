/** The aliases a command is typed as, shortest first, at most two ("L", "CO · CP"); the option the
 *  command takes follows each ("GC PAR"). Empty when the alias table has none for it. Only an
 *  alias that is the command alone counts (not the user's `LAYOFF A-WALL`). */
export function aliasesFor(command: string, aliases: Record<string, string> = DEFAULT_ALIASES): string[] {
  const line = COMMAND_LINE[command];
  if (!line) return [];
  const [name, option] = line;
  return Object.entries(aliases)
    .filter(([, target]) => target.trim().toUpperCase() === name)
    .map(([alias]) => alias.toUpperCase())
    .sort((a, b) => a.length - b.length || a.localeCompare(b))
    .slice(0, 2)
    .map((a) => (option ? `${a} ${option}` : a));
}
