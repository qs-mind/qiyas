/** The headline tools, drawn at the primary size: a group made only of them is one row of large
 *  buttons; every other group is two rows of standard ones. */
export const HEADLINE = new Set(["select", "distance", "area", "count", "exportTakeoff", "importBoq", "compare", "exportConflicts"]);

export const isPrimaryGroup = (g: RibbonGroup) => g.buttons.length > 0 && g.buttons.every((b) => HEADLINE.has(b.command));

